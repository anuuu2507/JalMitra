"""
JalMitra — Hardware-Ready Sensor Abstraction Layer
=================================================
This module provides an extensible sensor abstraction interface.
In the current prototype, all readings are generated by the SimulatedWaterLevelProvider.
The FutureSensorProvider interface defines how an ESP32 microcontroller with a waterproof
ultrasonic sensor (e.g. JSN-SR04T) will seamlessly stream telemetry into the backend in Phase 2.

HARDWARE INTEGRATION SPECIFICATION (For Future Deployment):
-----------------------------------------------------------
1. Microcontroller: ESP32-WROOM-32D / ESP8266 (Wi-Fi + optional 4G/LTE SIM7600 module for remote villages)
2. Sensor: JSN-SR04T waterproof ultrasonic transducer mounted at the top lid of the community overhead tank.
3. Measurement Formula:
     Water Depth (d_w) = Total Tank Height (H) - Sensor Distance Reading (d_s)
     Water Percentage (%) = (d_w / Maximum Water Height) * 100
4. Telemetry Endpoint:
     POST /api/sensors/esp32/telemetry
     Payload: {"device_id": "ESP32-WARD4-01", "tank_id": 1, "raw_distance_cm": 42.5, "api_key": "..."}
"""

import abc
import datetime
from typing import Dict, Any, Optional

class BaseWaterLevelProvider(abc.ABC):
    """Abstract interface that all water level sensor providers must implement."""

    @abc.abstractmethod
    def get_provider_name(self) -> str:
        """Returns the human-readable identifier of the provider."""
        pass

    @abc.abstractmethod
    def is_hardware_connected(self) -> bool:
        """Returns True if a physical device is verified connected."""
        pass

    @abc.abstractmethod
    def read_level(self, current_level_pct: float) -> float:
        """Returns water level percentage between 0.0 and 100.0."""
        pass

    @abc.abstractmethod
    def get_status_metadata(self) -> Dict[str, Any]:
        """Provides status details for UI and diagnostics."""
        pass


class SimulatedWaterLevelProvider(BaseWaterLevelProvider):
    """
    Simulated sensor provider for demo, testing, and competition presentation.
    Explicitly flags all data as simulated to prevent misrepresentation.
    """

    def __init__(self):
        self.provider_name = "Simulated Sensor Provider (Software Mock)"
        self.device_connected = False  # Explicit: No physical hardware connected

    def get_provider_name(self) -> str:
        return self.provider_name

    def is_hardware_connected(self) -> bool:
        return False

    def read_level(self, current_level_pct: float) -> float:
        # Clamps percentage within valid bounds
        return max(0.0, min(100.0, round(current_level_pct, 1)))

    def simulate_consumption(self, current_level_pct: float, step: float = 15.0) -> float:
        """Simulates community water draw-down."""
        return max(0.0, round(current_level_pct - step, 1))

    def simulate_refill(self, current_level_pct: float, step: float = 25.0) -> float:
        """Simulates pump/supply tank recharge."""
        return min(100.0, round(current_level_pct + step, 1))

    def get_status_metadata(self) -> Dict[str, Any]:
        return {
            "provider": self.provider_name,
            "status": "Simulated Sensor Connected",
            "hardware_connected": False,
            "simulation_mode": True,
            "sampling_frequency_sec": 60,
            "simulated_noise_pct": 0.2,
            "disclaimer": "Simulated sensor environment. No physical ultrasonic transducer or ESP32 connected."
        }


class FutureSensorProvider(BaseWaterLevelProvider):
    """
    Template and contract for Phase-2 physical hardware integration.
    Handles distance-to-volume conversion for cylindrical/rectangular overhead tanks.
    Currently in stub mode — ready for deployment when field hardware is installed.
    """

    def __init__(self, device_id: str, tank_height_cm: float = 300.0, dead_zone_cm: float = 20.0):
        self.device_id = device_id
        self.tank_height_cm = tank_height_cm
        self.dead_zone_cm = dead_zone_cm
        self.last_heartbeat: Optional[datetime.datetime] = None

    def get_provider_name(self) -> str:
        return f"ESP32-JSN-SR04T Provider ({self.device_id})"

    def is_hardware_connected(self) -> bool:
        # Will check active heartbeat within last 180 seconds when deployed
        return False

    def calculate_level_from_distance(self, distance_cm: float) -> float:
        """
        Calculates water level % from ultrasonic distance measurement.
        Ultrasonic sensor mounted on top: shorter distance = fuller tank.
        """
        effective_height = self.tank_height_cm - self.dead_zone_cm
        if effective_height <= 0:
            return 0.0
        
        water_depth = self.tank_height_cm - distance_cm
        pct = (water_depth / effective_height) * 100.0
        return max(0.0, min(100.0, round(pct, 1)))

    def read_level(self, current_level_pct: float) -> float:
        # Hardware not connected in this prototype
        return current_level_pct

    def get_status_metadata(self) -> Dict[str, Any]:
        return {
            "provider": self.get_provider_name(),
            "status": "Planned — Not Connected",
            "hardware_connected": False,
            "device_id": self.device_id,
            "target_microcontroller": "ESP32-WROOM-32 / ESP8266",
            "target_sensor": "JSN-SR04T Waterproof Ultrasonic",
            "note": "Hardware integration architecture is fully designed. Ready for field sensor connection."
        }


